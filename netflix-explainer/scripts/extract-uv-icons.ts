/** Pull the JSX between <Icon ...> and </Icon>, then strip one indent level. */
const extractInner = (source: string): string | null => {
  const match = source.match(/<Icon \{\.\.\.props\}[^>]*>\n([\s\S]*?)\n\s*<\/Icon>/);
  if (!match) return null;

  return match[1]
    .split("\n")
    .map((line) => (line.startsWith("    ") ? line.slice(4) : line))
    .join("\n");
};

const recolor = (markup: string): string =>
  Object.entries(COLOR_SLOTS).reduce(
    (acc, [hex, cssVar]) =>
      acc.split(`fill="${hex}"`).join(`fill="${cssVar}"`),
    markup,
  );

const available = new Set(
  readdirSync(UV_GENERATED)
    .filter((f) => f.endsWith("ProductIcon.tsx"))
    .map((f) => basename(f, "ProductIcon.tsx")),
);

mkdirSync(OUT_DIR, { recursive: true });

const emitted: string[] = [];
const missing: string[] = [];

for (const name of WANTED) {
  if (!available.has(name)) {
    missing.push(name);
    continue;
  }

  const source = readFileSync(
    join(UV_GENERATED, `${name}ProductIcon.tsx`),
    "utf8",
  );
  const inner = extractInner(source);

  if (!inner) {
    missing.push(`${name} (no <Icon> body)`);
    continue;
  }

  const component = `${name}Icon`;
  writeFileSync(
    join(OUT_DIR, `${component}.tsx`),
    `/**
 * Derived from @ultraviolet/icons ${name}ProductIcon (Scaleway, Apache-2.0).
 * Generated by scripts/extract-uv-icons.ts — do not edit by hand.
 */
import type { UvIconProps } from "./types";

export const ${component}: React.FC<UvIconProps> = ({ size = 64, style }) => (
  <svg
    fill="none"
    height={size}
    style={style}
    viewBox="0 0 64 64"
    width={size}
    xmlns="http://www.w3.org/2000/svg"
  >
${recolor(inner)
  .split("\n")
  .map((l) => (l.trim() ? `    ${l}` : l))
  .join("\n")}
  </svg>
);
`,
    "utf8",
  );

  emitted.push(component);
}

writeFileSync(
  join(OUT_DIR, "types.ts"),
  `import type { CSSProperties } from "react";

export type UvIconProps = {
  readonly size?: number;
  readonly style?: CSSProperties;
};
`,
  "utf8",
);

writeFileSync(
  join(OUT_DIR, "index.ts"),
  `/** Generated by scripts/extract-uv-icons.ts — do not edit by hand. */
export type { UvIconProps } from "./types";
${emitted.map((c) => `export { ${c} } from "./${c}";`).join("\n")}
`,
  "utf8",
);

console.log(`Extracted ${emitted.length} icons to src/deep/icons`);
if (missing.length) console.warn(`Missing: ${missing.join(", ")}`);
