/**
 * Extracts Scaleway Ultraviolet ProductIcon artwork into standalone, dependency-free
 * Remotion components.
 *
 * Why not import @ultraviolet/icons directly? The source components rely on
 * vanilla-extract (build-time CSS-in-JS) plus a theme provider, which would drag a
 * bundler plugin into Remotion's render pipeline. The SVG geometry is the part we
 * actually want, so we lift it verbatim and swap the baked-in Scaleway purples for
 * CSS custom properties, letting each scene retheme the same artwork at runtime.
 *
 * Source: packages/icons/src/components/ProductIcon/__generated__ (Apache-2.0)
 * Run: npx tsx scripts/extract-uv-icons.ts
 */
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";

const UV_GENERATED = join(
  import.meta.dirname,
  "../../packages/icons/src/components/ProductIcon/__generated__",
);
const OUT_DIR = join(import.meta.dirname, "../src/deep/icons");

/** Ultraviolet bakes the `primary` variant colours into the generated markup. */
const COLOR_SLOTS: Record<string, string> = {
  // fillWeak — the rounded plate behind the glyph
  "#eef": "var(--uv-weak)",
  "#f1eefc": "var(--uv-weak)",
  "#fff": "var(--uv-weak)",
  // fill — the main glyph body
  "#4f0599": "var(--uv-base)",
  "#521094": "var(--uv-base)",
  // fillStrong — accents and highlights
  "#a365f6": "var(--uv-strong)",
  "#a060f6": "var(--uv-strong)",
  "#bf95f9": "var(--uv-strong)",
};

